import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { chmod, copyFile, mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = new URL('../', import.meta.url);
const output = new URL('dist/', root);
const stage = new URL('cli/', output);
const manifest = JSON.parse(await readFile(new URL('packages/cli/package.json', root), 'utf8'));
await mkdir(stage, { recursive: true });

// One release for Brew and npm; internal workspaces remain private.
const bundled = await build({
  absWorkingDir: fileURLToPath(root),
  entryPoints: ['packages/cli/src/index.ts'],
  alias: {
    '@clqn/shared': './packages/shared/src/index.ts',
    '@clqn/mcp': './packages/mcp/src/index.ts',
  },
  outfile: fileURLToPath(new URL('clqn.mjs', stage)),
  bundle: true,
  platform: 'node',
  target: 'node22',
  format: 'esm',
  minify: true,
  keepNames: true,
  banner: { js: "import { createRequire } from 'node:module'; const require = createRequire(import.meta.url);" },
  legalComments: 'eof',
  metafile: true,
});
// Preserve the licenses of dependencies included in the bundle.
const dependencies = new Set(
  Object.keys(bundled.metafile.inputs)
    .map((input) => input.match(/^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//)?.[1])
    .filter(Boolean),
);
const licenses = [];
for (const directory of [...dependencies].sort()) {
  const url = new URL(`${directory}/`, root);
  const dependency = JSON.parse(await readFile(new URL('package.json', url), 'utf8'));
  for (const name of (await readdir(url)).filter((name) => /^licen[cs]e(?:[.-]|$)/i.test(name)).sort()) {
    licenses.push(`${dependency.name}@${dependency.version}\n\n${await readFile(new URL(name, url), 'utf8')}`);
  }
}
await writeFile(new URL('THIRD_PARTY_LICENSES.txt', stage), licenses.join('\n\n---\n\n'));
await chmod(new URL('clqn.mjs', stage), 0o755);
await writeFile(
  new URL('package.json', stage),
  `${JSON.stringify(
    {
      name: 'clqn-cli',
      version: manifest.version,
      description: 'Your agents. My agents. One workspace.',
      license: 'MIT',
      homepage: 'https://clqn.org/',
      repository: { type: 'git', url: 'git+https://github.com/clqn-org/clqn.git' },
      bugs: { url: 'https://github.com/clqn-org/clqn/issues' },
      keywords: ['cli', 'mcp', 'agents', 'collaboration'],
      engines: { node: '>=22.12.0' },
      bin: { clqn: 'clqn.mjs' },
      files: ['clqn.mjs', 'THIRD_PARTY_LICENSES.txt'],
      publishConfig: { access: 'public' },
    },
    null,
    2,
  )}\n`,
);
for (const name of ['README.md', 'LICENSE.md']) {
  await copyFile(new URL(name, root), new URL(name, stage));
}
// npm exposes the CLI entry point even when Windows starts it through npm.cmd.
const npmCli = process.env.npm_execpath;
const [packed] = JSON.parse(
  execFileSync(
    npmCli ? process.execPath : 'npm',
    [...(npmCli ? [npmCli] : []), 'pack', '--json', '--ignore-scripts', '--pack-destination', fileURLToPath(output)],
    { cwd: stage, encoding: 'utf8' },
  ),
);
const archive = await readFile(new URL(packed.filename, output));
const sha256 = createHash('sha256').update(archive).digest('hex');
await writeFile(
  new URL('clqn.rb', output),
  `# Generated by npm run package:cli. Copy to Formula/clqn.rb when releasing.
class Clqn < Formula
  desc "Shared workspaces for humans and their AI agents"
  homepage "https://clqn.org/"
  url "https://github.com/clqn-org/clqn/releases/download/v${manifest.version}/${packed.filename}"
  sha256 "${sha256}"
  license "MIT"

  depends_on "node"

  def install
    libexec.install "clqn.mjs"
    pkgshare.install "LICENSE.md", "THIRD_PARTY_LICENSES.txt"
    (bin/"clqn").write_env_script libexec/"clqn.mjs", PATH: "#{Formula["node"].opt_bin}:$PATH"
  end

  test do
    assert_equal version.to_s, shell_output("#{bin}/clqn --version").strip
    assert_match "Your agents. My agents. One workspace.", shell_output("#{bin}/clqn --help")
  end
end
`,
);
console.log(`Created dist/${packed.filename} and dist/clqn.rb`);
